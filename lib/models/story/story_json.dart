// Lenient JSON readers shared by the story models.

/// The enum value named [name], or [fallback].
T storyEnumByName<T extends Enum>(List<T> values, Object? name, T fallback) {
  for (final v in values) {
    if (v.name == name) return v;
  }
  return fallback;
}

List<String> storyStringList(Object? raw) =>
    (raw as List?)?.map((e) => e.toString()).toList() ?? [];

String storyStr(Object? raw) => raw?.toString() ?? '';
